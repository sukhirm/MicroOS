//! Embedded Bitmap Icon Engine.
//!
//! Provides compact 16x16 pixel icons with transparency support,
//! dynamic tinting, and palette mapping for desktop applications and window chrome.

use super::color::Color;
use super::surface::Surface;

/// Represents an embedded raster icon with a transparent palette index map.
pub struct Icon {
    pub width: u32,
    pub height: u32,
    pub data: &'static [u8],
}

impl Icon {
    /// Palette index 0: Transparent.
    pub const TRANSPARENT: u8 = 0;
    /// Palette index 1: Light text / primary foreground.
    pub const PRIMARY: u8 = 1;
    /// Palette index 2: Accent Azure / brand highlight.
    pub const ACCENT: u8 = 2;
    /// Palette index 3: Dark border / muted slate.
    pub const BORDER: u8 = 3;
    /// Palette index 4: Success green.
    pub const SUCCESS: u8 = 4;
    /// Palette index 5: Warning amber.
    pub const WARNING: u8 = 5;
    /// Palette index 6: Danger red.
    pub const DANGER: u8 = 6;
}

/// Draws an embedded icon on `surface` at `(start_x, start_y)`.
///
/// If `tint` is `Some(color)`, all non-transparent pixels are colored with `color`.
/// If `tint` is `None`, standard palette mapping is applied.
pub fn draw_icon(
    surface: &mut Surface,
    start_x: i32,
    start_y: i32,
    icon: &Icon,
    tint: Option<Color>,
) {
    let w = icon.width as i32;
    let h = icon.height as i32;

    for row in 0..h {
        for col in 0..w {
            let idx = (row * w + col) as usize;
            if idx >= icon.data.len() {
                continue;
            }

            let val = icon.data[idx];
            if val == Icon::TRANSPARENT {
                continue; // Transparent pixel: do not draw
            }

            let color = match tint {
                Some(t) => t,
                None => match val {
                    Icon::PRIMARY => Color::TEXT_LIGHT,
                    Icon::ACCENT => Color::ACCENT_AZURE,
                    Icon::BORDER => Color::BORDER_SLATE,
                    Icon::SUCCESS => Color::SUCCESS_GREEN,
                    Icon::WARNING => Color::WARNING_AMBER,
                    Icon::DANGER => Color::DANGER_RED,
                    _ => Color::TEXT_LIGHT,
                },
            };

            surface.set_pixel(start_x + col, start_y + row, color);
        }
    }
}

